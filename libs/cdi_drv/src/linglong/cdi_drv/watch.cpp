namespace fs = std::filesystem;
using utils::error::Result;
using utils::filelock::LockType;
using Units = std::map<std::string, std::string>;
constexpr std::string_view unitPrefix = "ll-cdi-drv-watch@";
constexpr std::string_view requestUnitPrefix = "ll-cdi-drv-request@";

std::string escapeInstance(std::string_view name)
{
    std::string escaped;
    for (const unsigned char ch : name) {
        if ((ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') || (ch >= '0' && ch <= '9')
            || ch == ':' || ch == '_' || ch == '.') {
            escaped += static_cast<char>(ch);
        } else {
            escaped += fmt::format("\\x{:02x}", ch);
        }
    }
    return escaped;
}

Result<std::string> makeWatch(const std::string &instance, const std::vector<std::string> &paths)
{
    LINGLONG_TRACE("generate CDI path unit");

    std::string content = "# Generated by ll-cdi-drv. Do not edit.\n"
                          "[Unit]\nDescription=Watch CDI driver inputs\n\n[Path]\n";
    content += fmt::format("Unit={}{}.service\n", requestUnitPrefix, instance);
    for (const auto &path : paths) {
        // PathChanged uses a whole line, rather than shell or C-style quoting.
        if (!fs::path(path).is_absolute() || path.find_first_of("\r\n") != std::string::npos
            || path.back() == '\\' || path.back() == ' ' || path.back() == '\t') {
            return LINGLONG_ERR("watchPathChanged requires an absolute, single-line systemd path");
        }
        // Preserve systemd specifiers, such as %v. Use %% for a literal percent sign.
        content += "PathChanged=" + path + '\n';
    }
    return content;
}

std::string watchUnitName(const std::string &name)
{
    return std::string(unitPrefix) + escapeInstance(name) + ".path";
}

Result<bool> pathExists(const fs::path &path)
{
    LINGLONG_TRACE(fmt::format("check CDI watch path {}", path));
    std::error_code ec;
    const bool exists = fs::exists(path, ec);
    if (ec) {
        return LINGLONG_ERR("check CDI watch path", ec);
    }
    return exists;
}

Result<void> collectUnitNames(const fs::path &directory, std::set<std::string> &names)
{
    LINGLONG_TRACE("list managed CDI path units");

    std::error_code ec;
    fs::directory_iterator entries(directory, ec);
    if (ec == std::errc::no_such_file_or_directory) {
        return LINGLONG_OK;
    }
    while (!ec && entries != fs::directory_iterator{}) {
        const auto path = entries->path();
        const auto name = path.filename().string();
        if (name.compare(0, unitPrefix.size(), unitPrefix) == 0 && path.extension() == ".path") {
            names.insert(name);
        }
        entries.increment(ec);
    }
    if (ec) {
        return LINGLONG_ERR("enumerate generated CDI path units", ec);
    }
    return LINGLONG_OK;
}

Result<void> controlUnits(const std::string &systemctl,
                          const std::string &action,
                          const std::set<std::string> &units)
{
    LINGLONG_TRACE("control CDI path units");

    if (units.empty()) {
        return LINGLONG_OK;
    }
    std::vector<std::string> args{ "--no-block", action, "--" };
    args.insert(args.end(), units.begin(), units.end());
    auto result = utils::Cmd(systemctl).exec(args);
    if (!result) {
        return LINGLONG_ERR(result);
    }
    return LINGLONG_OK;
}

