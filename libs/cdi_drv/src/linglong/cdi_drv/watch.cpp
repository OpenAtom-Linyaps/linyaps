Result<std::optional<std::string>> generateWatch(const std::string &name,
                                                 const types::CdiDrvConfig &config)
{
    LINGLONG_TRACE("prepare CDI path unit " + name);

    if (!config.watchPathChanged || config.watchPathChanged->empty()) {
        return LINGLONG_OK;
    }

    const auto instance = escapeInstance(name);
    if (requestUnitPrefix.size() + instance.size() + std::string_view(".service").size() > 255) {
        return LINGLONG_ERR("systemd unit name is too long");
    }
    auto content = makeWatch(instance, *config.watchPathChanged);
    if (!content) {
        return LINGLONG_ERR(content);
    }
    return std::move(*content);
}

Result<void> syncWatches(const WatchFiles &watches,
                         const RefreshRequests &requests,
                         const WatchOptions &options)
{
    LINGLONG_TRACE("synchronize CDI path units");

    const auto &unitDir = options.unitDir;
    const auto &systemctl = options.systemctl;
    std::error_code ec;
    fs::create_directories(unitDir, ec);
    if (ec) {
        return LINGLONG_ERR("create systemd runtime unit directory", ec);
    }

    auto lock =
      utils::filelock::FileLock::create(unitDir / ".ll-cdi-drv-watch.lock", LockType::Write);
    if (!lock) {
        return LINGLONG_ERR(lock);
    }
    auto acquired = lock->lock(LockType::Write);
    if (!acquired) {
        return LINGLONG_ERR(acquired);
    }

    Units desired;
    for (const auto &[name, content] : watches) {
        if (requests.all || requests.names.find(name) != requests.names.end()) {
            desired.emplace(watchUnitName(name), content);
        }
    }

    std::set<std::string> removed;
    std::set<std::string> restart;
    std::set<std::string> names;
    if (requests.all) {
        auto collected = collectUnitNames(unitDir, names);
        if (!collected) {
            return LINGLONG_ERR(collected);
        }
    } else {
        for (const auto &name : requests.names) {
            names.insert(watchUnitName(name));
        }
    }
    for (const auto &name : names) {
        if (desired.find(name) != desired.end()) {
            continue;
        }
        auto exists = pathExists(unitDir / name);
        if (!exists) {
            return LINGLONG_ERR(exists);
        }
        if (*exists) {
            removed.insert(name);
        }
    }

    // Stop obsolete watches before removing their unit definitions.
    auto stopped = controlUnits(systemctl, "stop", removed);
    if (!stopped) {
        return LINGLONG_ERR(stopped);
    }
    for (const auto &name : removed) {
        fs::remove(unitDir / name, ec);
        if (ec) {
            return LINGLONG_ERR("remove obsolete CDI path unit", ec);
        }
    }

    if (!desired.empty()) {
        auto staging = utils::TemporaryDirectory::create(".ll-cdi-drv-watch-", unitDir);
        if (!staging) {
            return LINGLONG_ERR(staging);
        }
        for (const auto &[name, content] : desired) {
            const auto path = staging->path() / name;
            auto written = utils::writeFile(path, content);
            if (!written) {
                return LINGLONG_ERR(written);
            }
            fs::rename(path, unitDir / name, ec);
            if (ec) {
                return LINGLONG_ERR("publish CDI path unit", ec);
            }
            restart.insert(name);
        }
    }
    auto reloaded = utils::Cmd(systemctl).exec({ "daemon-reload" });
    if (!reloaded) {
        return LINGLONG_ERR(reloaded);
    }
    return controlUnits(systemctl, "restart", restart);
}

