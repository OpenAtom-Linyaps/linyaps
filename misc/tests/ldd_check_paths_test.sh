set -euo pipefail

helper="$(dirname "${BASH_SOURCE[0]}")/../libexec/linglong/builder/helper/ldd-check.sh"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
mkdir "$tmp/first path" "$tmp/second path"
export LINGLONG_DEPENDS_FILE="$tmp/depends.yaml"
unset LINGLONG_LD_SO_CACHE

assert_paths() {
    rm -f "$LINGLONG_DEPENDS_FILE"
    bash "$helper" "$1"
    if [[ $(cat "$LINGLONG_DEPENDS_FILE") != $'# DO NOT EDIT THIS FILE, GENERATED BY ldd-check.sh\n\ndepends: []' ]]; then
        echo 'Unexpected dependency output' >&2
        exit 1
    fi
}

assert_paths "$tmp/first path:$tmp/second path"
assert_paths ":$tmp/first path::$tmp/second path:"
assert_paths "$tmp/first path"
rm "$LINGLONG_DEPENDS_FILE"
if output=$(bash "$helper" ':::' 2>&1); then
    echo 'Expected colon-only input to fail' >&2
    exit 1
else
    status=$?
fi
if [[ $status -ne 255 || $output != *'No paths provided'* || -e $LINGLONG_DEPENDS_FILE ]]; then
    printf 'Wrong colon-only failure (status %s): %s\n' "$status" "$output" >&2
    exit 1
fi

echo 'ldd-check paths: 4 cases passed'
